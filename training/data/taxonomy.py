"""Seed taxonomy for synthetic training data generation.

The corpus is generated by crossing (seed idea) × (agent within a crew), not
by inventing a parallel prompt set — each agent's real system prompt
(`ai/prompts/**`) and real Pydantic schema (`ai/schemas/`) are reused
directly, so the corpus teaches the model to do exactly what the live
pipeline asks of it.

Seed ideas are deliberately synthetic and varied across category, stage, and
"quality band" (how well-formed the raw idea text is) — production traffic
includes everything from a two-sentence fragment to a paragraph with a full
business case, and the model needs to handle both without the training
distribution implicitly requiring polished input.
"""

from dataclasses import dataclass, field
from enum import Enum
from typing import List


class QualityBand(str, Enum):
    """How well-formed the raw idea text is -- production traffic spans all three."""

    FRAGMENT = "fragment"          # one or two sentences, underspecified
    STANDARD = "standard"          # a clear paragraph, the common case
    DETAILED = "detailed"          # multi-paragraph with market/business context already stated


@dataclass(frozen=True)
class SeedIdea:
    """One synthetic startup idea used to generate training examples for
    every agent in the pipeline (implemented and specified alike)."""

    id: str
    category: str  # matches ai.shared.constants.StartupCategory values
    quality_band: QualityBand
    idea_text: str


